#!/usr/bin/env python3
"""
extract-words.py
One-time script to generate words.js from the Hunspell Macedonian dictionary.

Usage:
    1. Download mk_MK.dic:
       curl -o mk_MK.dic https://raw.githubusercontent.com/gerazov/dictionary-mk/master/dict-mk/mk_MK.dic
    2. Run: python3 extract-words.py
    3. Curate ANSWERS in words.js — remove proper nouns, keep everyday words.
"""

import sys
from pathlib import Path

INPUT  = Path('mk_MK.dic')
OUTPUT = Path('words.js')

# Full Macedonian Cyrillic alphabet (lowercase)
MK_ALPHA = set('абвгдѓежзѕијклљмнњопрстќуфхцчџш')

# Common Macedonian word-ending suffixes (reliably common words, not surnames)
COMMON_ENDINGS = {
    'ТА', 'ТО', 'ТЕ', 'ОТ', 'НА', 'НО', 'НИ', 'НЕ',
    'КИ', 'КА', 'КО', 'ЊЕ', 'ЊА', 'МЕ', 'АТ', 'АМ',
    'АШ', 'ЕЛ', 'СТА', 'СТО', 'АЛА', 'ЕТО',
}

# Surname-only endings to exclude from ANSWERS
SURNAME_ENDINGS = {'ЕВ', 'ЕВА', 'ЕВИ', 'ОВ', 'ОВА', 'ОВИ', 'ИЌ', 'ИЧ'}


def chunk(lst, n):
    for i in range(0, len(lst), n):
        yield lst[i:i+n]


def fmt_array(words, indent=2):
    sp = ' ' * indent
    return ',\n'.join(
        sp + ', '.join(f'"{w}"' for w in row)
        for row in chunk(words, 8)
    )


def main():
    if not INPUT.exists():
        print(f'Error: {INPUT} not found.')
        print('Download it first:')
        print('  curl -o mk_MK.dic https://raw.githubusercontent.com/gerazov/dictionary-mk/master/dict-mk/mk_MK.dic')
        sys.exit(1)

    lines = INPUT.read_text(encoding='cp1251').splitlines()

    # First line is the word count — skip it
    all_words = []
    for line in lines[1:]:
        bare = line.split('/')[0].strip()
        if not bare:
            continue
        # Skip proper nouns (first letter is uppercase Cyrillic)
        if bare[0].isupper():
            continue
        # Must be exactly 6 Unicode characters
        if len(bare) != 6:
            continue
        # All characters must be Macedonian Cyrillic letters
        if not all(c in MK_ALPHA for c in bare.lower()):
            continue
        all_words.append(bare.upper())

    valid_guesses = sorted(set(all_words))

    # ANSWERS candidates: common word endings, no surname endings
    answers = [
        w for w in valid_guesses
        if any(w.endswith(e) for e in COMMON_ENDINGS)
        and not any(w.endswith(e) for e in SURNAME_ENDINGS)
    ]

    # Words in VALID_GUESSES but not ANSWERS (to avoid duplication via spread)
    answers_set   = set(answers)
    extra_guesses = [w for w in valid_guesses if w not in answers_set]

    output = f'''// Word list for Шестерка — Macedonian 6-letter Wordle
// Derived from the OpenOffice Macedonian dictionary
// Originally developed by OSSM (Free/Libre Software Organisation of Macedonia)
// Source: https://github.com/gerazov/dictionary-mk
//
// Generated by extract-words.py — do not edit manually.
//
// ANSWERS (~{len(answers)} words): auto-filtered by common word endings.
//   ⚠️  NEEDS CURATION: review and remove proper nouns / obscure words.
//   Aim for ~500-1000 familiar everyday words.
//
// VALID_GUESSES ({len(valid_guesses)} words): all valid 6-letter Macedonian
//   Cyrillic words from the dictionary (used only for guess validation).

const ANSWERS = [
{fmt_array(answers)},
];

const VALID_GUESSES = [
  ...ANSWERS,
{fmt_array(extra_guesses)},
];
'''

    OUTPUT.write_text(output, encoding='utf-8')
    print(f'Written {OUTPUT}')
    print(f'  ANSWERS:       {len(answers):,}  (needs curation)')
    print(f'  VALID_GUESSES: {len(valid_guesses):,}')


if __name__ == '__main__':
    main()
